import { existsSync, readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const read = (path) => readFileSync(resolve(root, path), 'utf8')
const assert = (condition, message) => {
  if (!condition) throw new Error(message)
}

const app = read('src/App.tsx')
const styles = read('src/styles.css')
const nativeMain = read('native/src/main.rs')
const nativeMail = read('native/src/mail.rs')
const nativeSync = read('native/src/sync.rs')
const oauth = read('native/src/oauth.rs')
const tray = read('native/src/tray.rs')
const cargo = read('native/Cargo.toml')
const installer = read('scripts/install-portable.ps1')
const release = read('scripts/release-windows.ps1')

assert(!app.includes('accounts.export_encrypted'), 'renderer must not expose credential-bearing export')
assert(!app.includes('accounts.import_encrypted'), 'renderer must not expose credential-bearing import')
assert(!nativeMain.includes('accounts.export_encrypted'), 'native IPC must not expose credential-bearing export')
assert(!nativeMain.includes('accounts.import_encrypted'), 'native IPC must not expose credential-bearing import')
assert(!nativeMain.includes('            "mail.attachment" =>'), 'attachments must not expose the legacy one-shot IPC path')
assert(!existsSync(resolve(root, 'native/src/transfer.rs')), 'credential transfer implementation must stay removed')
assert(!cargo.includes('argon2 ='), 'credential-transfer-only KDF dependency must stay removed')

assert(nativeMain.includes('CREDENTIAL_ENVELOPE_PREFIX'), 'stored credentials must use a versioned envelope')
assert(nativeMain.includes('credential_binding(account)'), 'stored credentials must be bound to account connection metadata')
assert(nativeMain.includes('account connection settings changed; reauthorization required'), 'binding mismatch must fail closed')
assert(nativeMain.includes('legacy custom account credentials require reauthorization before connecting'), 'unbound custom credentials must never connect before reauthorization')
assert(nativeMain.includes('MAX_ACCOUNT_SIGNATURE_BYTES'), 'account signatures need a native UTF-8 byte budget')
assert(nativeMain.includes('"accounts.set_signature" =>'), 'account signature writes must cross the validated native IPC boundary')
assert(app.includes('appendAccountSignature(body, accountSignature)'), 'renderer must append the selected account signature only at send time')
assert(app.includes('textBody: outgoingBody'), 'plain-text sends must use the signature-appended body')
assert(app.includes('composeHtmlBody(outgoingBody, currentInlineImages)'), 'HTML sends must escape and render the same signature-appended body')

assert(oauth.includes('CALLBACK_REQUEST_DEADLINE'), 'OAuth callbacks need an absolute request deadline')
assert(oauth.includes('checked_duration_since(Instant::now())'), 'OAuth read timeout must shrink with the remaining deadline')
assert(oauth.includes('HTTP_TOTAL_TIMEOUT'), 'OAuth provider calls need an overall request deadline')
assert(oauth.includes('.timeout(total_timeout)'), 'OAuth provider deadlines must include response-body reads')
assert(oauth.includes('MAX_OAUTH_RESPONSE_BYTES'), 'OAuth JSON needs an explicit response-body limit')
assert(oauth.includes('.take((MAX_OAUTH_RESPONSE_BYTES + 1) as u64)'), 'OAuth JSON must be bounded before deserialization')
assert(!oauth.includes('.into_json()'), 'OAuth responses must not use unbounded JSON body reads')
assert(oauth.includes('MAX_ACCESS_TOKEN_BYTES'), 'OAuth access tokens need a field-size limit')
assert(oauth.includes('MAX_REFRESH_TOKEN_BYTES'), 'OAuth refresh tokens need a field-size limit')
assert(oauth.includes('MAX_VERIFICATION_URI_BYTES'), 'OAuth verification URLs need a field-size limit')

assert(nativeMail.includes('is_unsafe_attachment_format_character(character)'), 'attachment names must remove unsafe Unicode format controls')
assert(nativeMail.includes("'\\u{202a}'..='\\u{202e}'"), 'attachment names must remove bidi embedding and override controls')
assert(nativeMail.includes("'\\u{2066}'..='\\u{2069}'"), 'attachment names must remove bidi isolate controls')
assert(app.includes('<bdi dir="auto">{attachment.name}</bdi>'), 'attachment names must render inside a direction-isolating element')
assert(app.includes('DANGEROUS_ATTACHMENT_EXTENSIONS'), 'dangerous attachment suffixes must receive an explicit warning')
assert(styles.includes('unicode-bidi: isolate'), 'attachment filename styling must preserve direction isolation')

assert(nativeSync.includes('read_bounded_starttls_line'), 'STARTTLS plaintext lines must use a bounded reader')
assert(nativeSync.includes('MAX_STARTTLS_LINE_BYTES'), 'STARTTLS plaintext lines need an explicit byte budget')
assert(nativeSync.includes('MAX_STARTTLS_RESPONSE_BYTES'), 'STARTTLS plaintext exchange needs an aggregate byte budget')
assert(nativeSync.includes('STARTTLS_EXCHANGE_TIMEOUT'), 'STARTTLS plaintext exchange needs an absolute deadline')
assert(!nativeSync.includes(".read_until(b'\\n', &mut line)"), 'STARTTLS must not allocate through an unbounded delimiter read')
assert(nativeSync.includes('MAX_UID_SEARCH_RANGE_WIDTH'), 'IMAP UID searches need a fixed response-range ceiling')
assert(nativeSync.includes('search_uid_window('), 'IMAP UID range scans must use the bounded window helper')
assert(!nativeSync.includes('format!("UID {uid_floor}:*'), 'provider search must not request an unbounded UID result set')
assert(!nativeSync.includes('format!("UID {}:*"'), 'incremental sync must not request an unbounded UID result set')

assert(!tray.includes('FindWindowW'), 'single-instance activation must not trust a window title alone')
assert(tray.includes('QueryFullProcessImageNameW'), 'single-instance activation must verify the owning executable')
assert(tray.includes('find_main_window_for_process(GetCurrentProcessId())'), 'tray subclassing must stay within the current process')

assert(installer.includes('AllowUnsignedDevelopmentBuild'), 'unsigned installation must be explicitly development-only')
assert(installer.includes('portable ZIP installation is restricted to local source-build verification'), 'portable installation must fail closed outside explicit development use')
assert(installer.includes('verified signed MSIX for production'), 'production installation must route to whole-package signing')
assert(!installer.includes('TrustedSignerThumbprint'), 'an executable-only signature must not imply that portable renderer assets are authenticated')
assert(!release.includes('gh release create'), 'local release gate must not publish portable artifacts')
assert(!release.includes('[switch]$Publish'), 'portable release gate must not expose a publish switch')

assert(app.includes("label: 'Apple Connect 通知', icon: 'bell'"), 'Apple heuristic category must use neutral presentation')
assert(!app.includes("label: 'Apple Connect', icon: 'shieldCheck'"), 'heuristic From-domain classification must not imply verification')

console.log('security policy regression checks passed')
